list=['Milk','Chocolate','Maggie']
print(list)  # Output : ['Milk', 'Chocolate', 'Maggie']


# 1. append --> Adds the element at the end of the list
list.append('Orange')
print(list)  # Output : ['Milk', 'Chocolate', 'Maggie', 'Orange']


list.append('Grapes')
print(list)  # Output : ['Milk', 'Chocolate', 'Maggie', 'Orange', 'Grapes']
